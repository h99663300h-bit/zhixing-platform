const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
process.env.DATA_FILE = path.join(__dirname, 'backend-smoke-' + process.pid + '.json');
process.env.DEMO_SEED = '1';
process.env.DEMO_SEED = '1';
const { server } = require('../server');
let base;
const cookies = {};
async function request(url, method = 'GET', body, role) {
  const headers = {};
  if (body) headers['Content-Type'] = 'application/json';
  if (role && cookies[role]) headers.Cookie = cookies[role];
  const response = await fetch(base + url, { method, headers, body: body ? JSON.stringify(body) : undefined });
  const cookie = response.headers.get('set-cookie');
  if (role && cookie) cookies[role] = cookie.split(';')[0];
  return { status: response.status, data: await response.json() };
}
async function run() {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  base = 'http://127.0.0.1:' + server.address().port;
  assert.equal((await request('/api/health')).data.ok, true);
  const courses = (await request('/api/courses')).data.courses;
  assert.equal(courses.length, 3);
  const courseId = courses[0].id;
  const lessonId = courses[0].lessons[0].id;
  const student = await request('/api/auth/register','POST',{name:'测试学生',email:'student@example.edu',studentId:'20260001',password:'StrongPass123!'},'student');
  assert.equal(student.data.user.role,'student');
  assert.equal((await request('/api/auth/register','POST',{name:'重复学生',email:'other@example.edu',studentId:'20260001',password:'StrongPass123!'})).status,409);
  assert.equal((await request('/api/auth/me','GET',null,'student')).data.user.studentId,'20260001');
  assert.equal((await request('/api/courses','POST',{title:'No',description:'No',category:'No'},'student')).status,403);
  assert.equal((await request('/api/courses/'+courseId+'/quiz','GET',null,'student')).status,403);
  const teacherAuth = await request('/api/auth/login','POST',{email:'teacher@university.edu',password:'Teacher123!'},'teacher');
  assert.equal(teacherAuth.data.user.role,'teacher');
  const teacherCourse = (await request('/api/courses/'+courseId,'GET',null,'teacher')).data.course;
  assert.equal((await request('/api/courses/'+courseId+'/enroll','POST',{code:teacherCourse.enrollmentCode},'student')).status,200);
  assert.equal((await request('/api/lessons/'+lessonId+'/complete','POST',{},'student')).data.course.progress,33);
  const quiz = await request('/api/courses/'+courseId+'/quiz','GET',null,'student');
  assert.equal(quiz.status,200);
  assert.ok(!('correctIndex' in quiz.data.quiz.questions[0]));
  const answers = quiz.data.quiz.questions.map(q => ({questionId:q.id,optionIndex:999}));
  assert.equal((await request('/api/courses/'+courseId+'/quiz/submit','POST',{answers},'student')).data.attempt.score,0);
  const post = await request('/api/courses/'+courseId+'/discussions','POST',{content:'请解释这个概念'},'student');
  assert.equal(post.status,201);
  assert.equal((await request('/api/courses/'+courseId+'/discussions','GET',null,'student')).data.posts.length,1);
  const teacher = await request('/api/auth/login','POST',{email:'teacher@university.edu',password:'Teacher123!'},'teacher');
  assert.equal(teacher.data.user.role,'teacher');
  assert.equal((await request('/api/teacher/overview','GET',null,'teacher')).data.stats.totalStudents,1);
  assert.equal((await request('/api/teacher/students','GET',null,'teacher')).data.students[0].enrollments[0].progress,33);
  assert.equal((await request('/api/courses/'+courseId+'/discussions/'+post.data.post.id,'DELETE',null,'teacher')).status,200);
  const created = await request('/api/courses','POST',{title:'新增课程',description:'测试介绍',category:'测试',color:'#123456'},'teacher');
  assert.equal(created.status,201);
  const newId = created.data.course.id;
  const lesson = await request('/api/courses/'+newId+'/lessons','POST',{title:'第一节',type:'reading',content:'内容'},'teacher');
  assert.equal(lesson.status,201);
  assert.equal((await request('/api/lessons/'+lesson.data.lesson.id,'PATCH',{content:'更新内容'},'teacher')).data.lesson.content,'更新内容');
  assert.equal((await request('/api/courses/'+newId+'/quiz','PUT',{questions:[{text:'测试问题?',options:['A','B'],correctIndex:1}]},'teacher')).status,200);
  assert.equal((await request('/api/courses/'+newId,'DELETE',null,'teacher')).status,200);
  assert.equal((await request('/api/courses/'+newId)).status,404);
  console.log('PASS: registration, unique IDs, permissions, courses, lessons, progress, quiz, discussion, analytics');
}
run().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => server.close(() => { try { fs.unlinkSync(process.env.DATA_FILE); } catch {} }));
